def check_edge_cases() -> bool:
    print("== 4. degenerate inputs ==")
    ok = True
    rng = random.Random(99)
    values = random_initial_values(rng)
    parameters = random_parameters(rng)
    options = build_test_options(values, rng)

    # No warm-up at all: must still quote legally and price in range.
    maker = MarketMaker(underlyings(values), options, STARTING_CASH)
    for option in options:
        price = maker.price_option(option)
        assert 0.0 <= price <= 1.0, price
        quote = maker.quote(option, 7)
        assert 0.0 <= quote.bid_price < quote.offer_price <= 1.0
    print("   no warm_up: prices in range, quotes legal")

    # One-day, empty, and pinned-at-zero histories.
    for label, history in (
        ("single day", MarketHistory({uid: (values[uid],) for uid in ALL_IDS})),
        ("empty", MarketHistory({})),
        (
            "rate pinned at zero",
            MarketHistory(
                {
                    FED_FUNDS_RATE_UNDERLYING_ID: tuple(0.0 for _ in range(60)),
                    AJARAI_UNDERLYING_ID: tuple(100.0 + 0.5 * index for index in range(60)),
                    THERIODIC_UNDERLYING_ID: tuple(100.0 - 0.2 * index for index in range(60)),
                }
            ),
        ),
        (
            "flat values",
            MarketHistory({uid: tuple(values[uid] for _ in range(60)) for uid in ALL_IDS}),
        ),
    ):
        maker = MarketMaker(underlyings(values), options, STARTING_CASH)
        maker.warm_up(history)
        for option in options:
            assert 0.0 <= maker.price_option(option) <= 1.0
            assert 0.0 <= maker.price_option_from_parameters(parameters, option) <= 1.0
            quote = maker.quote(option, 7)
            assert 0.0 <= quote.bid_price < quote.offer_price <= 1.0
            assert quote.bid_quantity > 0 and quote.offer_quantity > 0
        print(f"   {label} history: quotes legal")

    # Contract shapes and balances the graded cases never contain. Round one only ever shows unit
    # leg weights, one-to-five-step expiries, books of three to ten, and balances of 10/20/40, so
    # nothing outside that has been exercised by a score. These lock in that it stays legal there.
    outside_envelope = [
        ("fractional leg weights", (OptionLeg(underlying_id=AJARAI_UNDERLYING_ID, weight=0.5),
                                    OptionLeg(underlying_id=THERIODIC_UNDERLYING_ID, weight=0.5)), 3),
        ("a rate leg mixed with a company leg", (OptionLeg(underlying_id=FED_FUNDS_RATE_UNDERLYING_ID, weight=1.0),
                                                 OptionLeg(underlying_id=AJARAI_UNDERLYING_ID, weight=-0.001)), 3),
        ("a zero-step option in the live book", (OptionLeg(underlying_id=AJARAI_UNDERLYING_ID, weight=1.0),), 0),
        ("a twenty-step option", (OptionLeg(underlying_id=THERIODIC_UNDERLYING_ID, weight=1.0),), 20),
    ]
    history = MarketHistory({uid: tuple(values[uid] for _ in range(30)) for uid in ALL_IDS})
    for label, legs, steps in outside_envelope:
        strike = 0.0 if len(legs) > 1 else round(values[legs[0].underlying_id] * 1.02, 2)
        option = BinaryOption(legs=legs, option_id=99, steps_until_expiry=steps, strike=strike)
        for cash in (1.0, 5.0, 250.0, 5000.0):
            maker = MarketMaker(underlyings(values), [option], cash)  # a book of exactly one
            maker.warm_up(history)
            price = maker.price_option(option)
            assert 0.0 <= price <= 1.0, (label, cash, price)
            quote = maker.quote(option, 7)
            assert 0.0 <= quote.bid_price < quote.offer_price <= 1.0, (label, cash, quote)
            assert quote.bid_quantity > 0 and quote.offer_quantity > 0, (label, cash, quote)
            # Never show a market that would lose money on its own valuation.
            assert quote.bid_price <= price + 1e-9 or steps == 0, (label, cash, quote, price)
            assert quote.offer_price >= price - 1e-9 or steps == 0, (label, cash, quote, price)
        print(f"   {label}: legal at every balance")

    # Enormous fill-or-kill orders must never be accepted beyond the cash buffer.
    maker = MarketMaker(underlyings(values), options, STARTING_CASH)
    maker.warm_up(MarketHistory({uid: tuple(values[uid] for _ in range(60)) for uid in ALL_IDS}))
    accepted_margin = 0.0
    for option in options:
        for side in (OrderType.BUY, OrderType.SELL):
            order = FokOrder(
                counterparty_id=1, option_id=option.option_id, order_type=side, price=0.5, quantity=100_000
            )
            if maker.respond_to_fok(option, order):
                accepted_margin += 50_000.0
    if accepted_margin > 0:
        ok = False
        print(f"   FAIL: accepted {accepted_margin:.0f} of margin on 100k-lot orders")
    else:
        print("   huge FOK orders: all declined")

    # Stress the cash model: thin balances, a long session, late settlement, a short warm-up.
    for label, kwargs in (
        ("zero-step settles next day", {"zero_step_settles_next_day": True}),
        ("short history", {"history_days": 30}),
        ("tiny cash (10)", {"starting_cash": 10.0}),
        ("small cash (40)", {"starting_cash": 40.0}),
        ("long session (200 days)", {"days": 200}),
        ("long session, tiny cash", {"days": 200, "starting_cash": 10.0}),
    ):
        for seed in (777, 778):
            arguments = {"days": 35, **kwargs}
            results = run_session(seed=seed, **arguments)
            status = "BANKRUPT" if results["__bankrupt__"] else "solvent"
            print(
                f"   {label} [seed {seed}]: bot {results['Telescoping Theo']:+.1f} "
                f"volume {results['__volume__']:.0f} ({status})"
            )
            if results["__bankrupt__"]:
                ok = False

    print(f"   {'PASS' if ok else 'FAIL'}")
    return ok


def check_flipped_fok_convention() -> bool:
    """If `order_type` meant our own side, the bot should notice and stop bleeding."""
    print("== 5. reversed FOK convention ==")
    rng = random.Random(5)
    values = random_initial_values(rng)
    parameters = random_parameters(rng)
    random.seed(4242)
    path = simulate_path(parameters, values, 120)
    history = MarketHistory({uid: tuple(day[uid] for day in path) for uid in ALL_IDS})
    values = path[-1]
    options = build_test_options(values, rng, count=12)
    maker = MarketMaker(underlyings(values), options, STARTING_CASH)
    maker.warm_up(history)

    accepted = 0
    for round_index in range(40):
        option = options[round_index % len(options)]
        if option.steps_until_expiry == 0:
            continue
        fair = maker.price_option(option)
        side = OrderType.BUY if round_index % 2 == 0 else OrderType.SELL
        price = round(min(0.99, fair + 0.12), 2) if side == OrderType.BUY else round(max(0.01, fair - 0.12), 2)
        order = FokOrder(counterparty_id=9, option_id=option.option_id, order_type=side, price=price, quantity=5)
        if maker.respond_to_fok(option, order):
            accepted += 1
            # Report the fill with the OPPOSITE sign to what the bot expects.
            quantity = 5 if side == OrderType.BUY else -5
            maker.on_trade(option, price, quantity, 9)
    flipped = maker._fok_side_flipped
    print(f"   accepted {accepted} orders, convention flipped: {flipped}")
    print(f"   {'PASS' if flipped else 'FAIL (never noticed)'}")
    return flipped


