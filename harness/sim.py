"""Local validation harness for `bot.py`. Not part of the graded submission.

Run with a Python that supports `StrEnum` (3.11+):

    python3.13 sim.py            # all checks
    python3.13 sim.py theo       # pricer vs Monte Carlo only
    python3.13 sim.py estimate   # parameter recovery only
    python3.13 sim.py session    # trading sessions only
    python3.13 sim.py edge       # degenerate inputs only

Checks, in order:
  1. `price_option_from_parameters` against Monte Carlo paths generated by `MarketParameters`
     itself -- this is what the THEO test scores.
  2. `warm_up` recovering the parameters, and `price_option` tracking the true-parameter price.
  3. Full trading sessions against competing market makers and informed counterparties, with the
     exchange's margin accounting, asserting no exception and no bankruptcy.
  4. Degenerate inputs: no history, a rate pinned at zero, zero-step options that settle a day
     late, huge fill-or-kill orders, a reversed fill-or-kill side convention.
"""

